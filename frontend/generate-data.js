const axios = require('axios');
const cheerio = require('cheerio');
const fs = require('fs');

async function getImageUrl(query) {
  try {
    const res = await axios.get(`https://www.bing.com/images/search?q=${encodeURIComponent(query)}&first=1`, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
      }
    });
    const $ = cheerio.load(res.data);
    let imgUrl = '';
    $('a.iusc').each((i, el) => {
      const m = $(el).attr('m');
      if (m) {
        const data = JSON.parse(m);
        if (data.murl) {
          imgUrl = data.murl;
          return false;
        }
      }
    });
    return imgUrl || 'https://images.unsplash.com/photo-1555396273-367ea4eb4db5?q=80&w=600&auto=format&fit=crop';
  } catch (e) {
    return 'https://images.unsplash.com/photo-1555396273-367ea4eb4db5?q=80&w=600&auto=format&fit=crop';
  }
}

