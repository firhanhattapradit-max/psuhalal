async function generateArray(key, arr) {
  let output = `const NARATHIWAT_${key.toUpperCase()}: Place[] = [\n`;
  for (let i = 0; i < arr.length; i++) {
    const p = arr[i];
    const query = p.name + ' นราธิวาส';
    console.log('Fetching image for:', query);
    const img = await getImageUrl(query);
    output += `  { id: 'nr_${key}_${i}', name: '${p.name}', description: '${p.description}', rating: ${p.rating}, type: '${p.type}', image: '${img}' },\n`;
    await new Promise(r => setTimeout(r, 500)); // sleep to avoid ban
  }
  output += '];\n';
  return output;
}

async function run() {
  const r = await generateArray('restaurants', places.restaurants);
  const a = await generateArray('attractions', places.attractions);
  const s = await generateArray('souvenirs', places.souvenirs);
  
  const code = r + '\n' + a + '\n' + s;
  fs.writeFileSync('generated-narathiwat.txt', code);
  console.log('Done!');
}

run();
