function prepareResources() {
  const flattened: Record<string, { translation: Record<string, string> }> = {};
  for (const lang of Object.keys(rawResources)) {
    const langObj = (rawResources as any)[lang];
    const trans: Record<string, string> = {};
    for (const section of Object.keys(langObj)) {
      const sectionObj = langObj[section];
      for (const key of Object.keys(sectionObj)) {
        const val = sectionObj[key];
        trans[`${section}.${key}`] = val;
        trans[key] = val;
      }
    }
    flattened[lang] = { translation: trans };
  }
  return flattened;
}

const resources = prepareResources();

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    lng: 'th',
    fallbackLng: 'th',
    interpolation: {
      escapeValue: false
    },
    react: {
      useSuspense: false
    }
  });

i18n.on('languageChanged', (lng) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lng;
    document.documentElement.dir = lng === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem('user_lang', lng);
    } catch (e) {}
  }
});

